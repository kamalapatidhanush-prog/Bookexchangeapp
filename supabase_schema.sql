create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and is_active
  );
$$;

create policy "active books are visible to authenticated users"
  on public.books for select using (is_active or public.is_admin());
create policy "admins manage books"
  on public.books for all using (public.is_admin()) with check (public.is_admin());
create policy "users view their borrowings"
  on public.borrowings for select using (auth.uid() = user_id or public.is_admin());
create policy "users view their notifications"
  on public.notifications for select using (auth.uid() = user_id or public.is_admin());
create policy "users update their notifications"
  on public.notifications for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users view their payment orders"
  on public.payment_orders for select using (auth.uid() = buyer_id or public.is_admin());
create policy "admins manage payment orders"
  on public.payment_orders for all using (public.is_admin()) with check (public.is_admin());

create or replace function public.create_payment_order(
  requested_transaction_id uuid,
  requested_book_title text,
  requested_amount numeric,
  requested_method text,
  requested_gift_card_code text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  order_id uuid;
begin
  if current_user_id is null then raise exception 'Authentication required'; end if;
  if requested_amount <= 0 then raise exception 'Invalid payment amount'; end if;
  if requested_method not in ('upi', 'card', 'pay_later', 'gift_card') then
    raise exception 'Unsupported payment method';
  end if;
  if requested_transaction_id is not null and not exists (
    select 1 from public.transactions
    where id = requested_transaction_id and buyer_id = current_user_id
  ) then
    raise exception 'Transaction not found';
  end if;
  if requested_method = 'gift_card' and not exists (
    select 1 from public.gift_cards
    where code = requested_gift_card_code and is_active and remaining_amount >= requested_amount
      and (expires_at is null or expires_at > now())
  ) then
    raise exception 'Gift card is invalid or has insufficient balance';
  end if;
  insert into public.payment_orders (
    buyer_id, transaction_id, book_title, amount, payment_method, gift_card_code
  ) values (
    current_user_id, requested_transaction_id, requested_book_title, requested_amount,
    requested_method, requested_gift_card_code
  ) returning id into order_id;
  return order_id;
end;
$$;

revoke all on function public.create_payment_order(uuid, text, numeric, text, text) from public;
grant execute on function public.create_payment_order(uuid, text, numeric, text, text) to authenticated;

create or replace function public.borrow_book(requested_book_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  selected_book public.books;
  borrowing_id uuid;
begin
  if current_user_id is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from public.profiles where id = current_user_id and is_active) then
    raise exception 'Your account is inactive';
  end if;
  if (select count(*) from public.borrowings where user_id = current_user_id and status = 'active') >= 5 then
    raise exception 'Borrowing limit reached';
  end if;
  select * into selected_book from public.books where id = requested_book_id and is_active for update;
  if not found then raise exception 'Book not found'; end if;
  if selected_book.available_copies < 1 then raise exception 'No copies are available'; end if;
  if exists (select 1 from public.borrowings where user_id = current_user_id and book_id = requested_book_id and status = 'active') then
    raise exception 'You already borrowed this book';
  end if;

  update public.books set available_copies = available_copies - 1, updated_at = now()
    where id = requested_book_id;
  insert into public.borrowings (user_id, book_id, book_title, due_date)
    values (current_user_id, selected_book.id, selected_book.title, now() + interval '21 days')
    returning id into borrowing_id;
  insert into public.notifications (user_id, title, body, type)
    values (current_user_id, 'Book borrowed', selected_book.title || ' is due in 21 days.', 'borrowed');
  return borrowing_id;
end;
$$;

create or replace function public.return_book(requested_borrowing_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  borrowing public.borrowings;
begin
  select * into borrowing from public.borrowings
    where id = requested_borrowing_id and (user_id = auth.uid() or public.is_admin()) for update;
  if not found then raise exception 'Borrowing not found'; end if;
  if borrowing.status = 'returned' then raise exception 'Book already returned'; end if;
  update public.borrowings set status = 'returned', returned_at = now(), updated_at = now()
    where id = requested_borrowing_id;
  update public.books set available_copies = least(total_copies, available_copies + 1), updated_at = now()
    where id = borrowing.book_id;
  insert into public.notifications (user_id, title, body, type)
    values (borrowing.user_id, 'Book returned', borrowing.book_title || ' has been returned.', 'returned');
end;
$$;

revoke all on function public.borrow_book(uuid) from public;
revoke all on function public.return_book(uuid) from public;
grant execute on function public.borrow_book(uuid) to authenticated;
grant execute on function public.return_book(uuid) to authenticated;

