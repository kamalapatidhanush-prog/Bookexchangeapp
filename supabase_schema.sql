  book_id uuid not null references public.books(id) on delete cascade,
  status text not null default 'waiting' check (status in ('waiting', 'available', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, book_id)
);

create table if not exists public.payment_orders (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  transaction_id uuid,
  book_title text not null,
  amount numeric(10, 2) not null check (amount > 0),
  currency text not null default 'GBP',
  payment_method text not null check (payment_method in ('upi', 'card', 'pay_later', 'gift_card')),
  provider text not null default 'not_configured',
  provider_order_id text,
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'paid', 'failed', 'cancelled')),
